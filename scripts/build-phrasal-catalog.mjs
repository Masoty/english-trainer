import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const seedPath = path.join(__dirname, "phrasal-seed.json");
const outTs = path.join(root, "src/data/phrasalVerbsExtended.ts");

function slug(phrase) {
  return phrase
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");
}

const seed = JSON.parse(fs.readFileSync(seedPath, "utf8"));

const items = seed.map((row, index) => {
  const id = 141 + index;
  const [phrase, uk, sentence] = row;
  const fileSlug = slug(phrase);
  const imageFile = `${fileSlug}.jpg`;
  return { id, phrase, uk, sentence, imageFile };
});

const ts = `/* Auto-generated by scripts/build-phrasal-catalog.mjs — do not edit by hand */
import type { PhrasalVerb } from "./phrasalVerbs";

export const phrasalVerbsExtended: PhrasalVerb[] = [
${items
  .map(
    (x) => `  {
    id: ${x.id},
    phrase: ${JSON.stringify(x.phrase)},
    phonetic: "",
    uk: ${JSON.stringify(x.uk)},
    sentence: ${JSON.stringify(x.sentence)},
    image: "/images/phrasal-verbs/${x.imageFile}",
  }`,
  )
  .join(",\n")}
];
`;

fs.writeFileSync(outTs, ts, "utf8");
console.log(`Updated ${items.length} entries (expect JPG at public/images/phrasal-verbs/*.jpg).`);
